#!/usr/bin/env python3
"""Rasterize a TTF into a TFT_eSPI smooth font (Processing .vlw format) as a C array.

    python -I tools/make_vlw.py --ttf Montserrat-Medium.ttf --size 150 --chars "0123456789.-" \
        --name font_digits_150 -o fonts/font_digits_150.h

VLW layout (big-endian int32): count, version 11, size, 0, ascent, descent;
then per glyph: unicode, height, width, xAdvance, topExtent(dY), leftExtent(dX), 0;
then each glyph's width*height 8-bit alpha bitmap. TFT_eSPI stores height,
width and xAdvance as uint8, so every glyph must stay below 256 px.
Requires Pillow.
"""
from __future__ import annotations

import argparse
import struct

from PIL import Image, ImageDraw, ImageFont


def glyph(font, ch, ascent, descent):
    pad = 8
    adv = font.getlength(ch)
    img = Image.new("L", (int(adv) + 2 * pad + 40, ascent + descent + 2 * pad), 0)
    base = pad + ascent
    ImageDraw.Draw(img).text((pad, base), ch, font=font, fill=255, anchor="ls")
    bbox = img.getbbox()
    if bbox is None:
        return dict(adv=round(adv), w=0, h=0, dy=0, dx=0, px=b"")
    x0, y0, x1, y1 = bbox
    return dict(adv=round(adv), w=x1 - x0, h=y1 - y0, dy=base - y0, dx=x0 - pad,
                px=img.crop(bbox).tobytes())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--size", type=int, required=True)
    ap.add_argument("--chars", default="".join(chr(c) for c in range(0x20, 0x7F)) + "·°")
    ap.add_argument("--name", required=True)
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()

    font = ImageFont.truetype(a.ttf, a.size)
    ascent, descent = font.getmetrics()
    chars = sorted(set(a.chars), key=ord)
    glyphs = [(c, glyph(font, c, ascent, descent)) for c in chars]

    out = bytearray(struct.pack(">6i", len(glyphs), 11, a.size, 0, ascent, descent))
    for c, g in glyphs:
        for k in ("w", "h", "adv"):
            assert 0 <= g[k] < 256, (c, k, g[k])
        out += struct.pack(">7i", ord(c), g["h"], g["w"], g["adv"], g["dy"], g["dx"], 0)
    for _, g in glyphs:
        out += g["px"]
    name = a.name.encode()
    out += bytes([len(name)]) + name + b"\0" + bytes([len(name)]) + name + b"\0" + b"\1"

    lines = [f"// Generated by tools/make_vlw.py: {a.ttf.replace(chr(92), '/').split('/')[-1]} {a.size}px, "
             f"{len(glyphs)} glyphs, ascent {ascent}, descent {descent}",
             "#pragma once", "#include <pgmspace.h>",
             f"const uint8_t {a.name}[] PROGMEM = {{"]
    for i in range(0, len(out), 24):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in out[i:i + 24]) + ",")
    lines.append("};")
    with open(a.out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{a.out}: {len(glyphs)} glyphs, {len(out)} bytes")


if __name__ == "__main__":
    main()
