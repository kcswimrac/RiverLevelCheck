#!/usr/bin/env python3
"""Rasterize a TTF into an LVGL 8 `lv_font_fmt_txt` C file (4 bpp, uncompressed).

A small local stand-in for lv_font_conv, used for the oversized stage digits.

    python tools/make_font.py --ttf lib/lvgl/scripts/built_in_font/Montserrat-Medium.ttf \
        --size 128 --chars "0123456789.-" --name font_stage_128 -o src/fonts/font_stage_128.c

Requires Pillow.
"""
from __future__ import annotations

import argparse
from PIL import Image, ImageDraw, ImageFont


def render_glyph(font: ImageFont.FreeTypeFont, ch: str, ascent: int, descent: int):
    pad = 8
    adv = font.getlength(ch)
    w = int(adv) + 2 * pad + 32
    h = ascent + descent + 2 * pad
    img = Image.new("L", (w, h), 0)
    baseline_y = pad + ascent
    ImageDraw.Draw(img).text((pad, baseline_y), ch, font=font, fill=255, anchor="ls")
    bbox = img.getbbox()
    if bbox is None:  # e.g. space
        return dict(adv=adv, w=0, h=0, ofs_x=0, ofs_y=0, px=[])
    x0, y0, x1, y1 = bbox
    px = [img.getpixel((x, y)) >> 4 for y in range(y0, y1) for x in range(x0, x1)]
    return dict(adv=adv, w=x1 - x0, h=y1 - y0, ofs_x=x0 - pad, ofs_y=baseline_y - y1, px=px)


def pack4(px: list[int]) -> list[int]:
    out = []
    for i in range(0, len(px), 2):
        hi = px[i]
        lo = px[i + 1] if i + 1 < len(px) else 0
        out.append((hi << 4) | lo)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--size", type=int, required=True)
    ap.add_argument("--chars", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()

    font = ImageFont.truetype(a.ttf, a.size)
    ascent, descent = font.getmetrics()
    chars = sorted(set(a.chars), key=ord)

    bitmap: list[int] = []
    dscs = []
    for ch in chars:
        g = render_glyph(font, ch, ascent, descent)
        for k in ("w", "h"):
            assert 0 <= g[k] <= 255, (ch, k, g[k])
        assert -128 <= g["ofs_x"] <= 127 and -128 <= g["ofs_y"] <= 127, ch
        dscs.append((ch, len(bitmap), round(g["adv"] * 16), g))
        bitmap.extend(pack4(g["px"]))
    assert len(bitmap) < (1 << 20)

    L = []
    L.append(f"/* Generated by tools/make_font.py: {a.ttf.split('/')[-1]} {a.size}px 4bpp")
    L.append(f" * Characters: {''.join(chars)!r} */")
    L.append('#include "lvgl.h"\n')
    L.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        L.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    L.append("};\n")
    L.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    L.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for ch, idx, adv, g in dscs:
        L.append(f"    {{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {g['w']}, .box_h = {g['h']}, "
                 f".ofs_x = {g['ofs_x']}, .ofs_y = {g['ofs_y']}}}, /* {ch!r} */")
    L.append("};\n")
    L.append("static const uint16_t unicode_list[] = {" +
             ", ".join(str(ord(c) - ord(chars[0])) for c in chars) + "};\n")
    L.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {{")
    L.append(f"    .range_start = {ord(chars[0])}, .range_length = {ord(chars[-1]) - ord(chars[0]) + 1}, "
             f".glyph_id_start = 1, .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, "
             f".list_length = {len(chars)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY")
    L.append("}};\n")
    L.append("static lv_font_fmt_txt_glyph_cache_t cache;")
    L.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    L.append("    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,")
    L.append("    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,")
    L.append("    .kern_classes = 0, .bitmap_format = 0, .cache = &cache")
    L.append("};\n")
    L.append(f"const lv_font_t {a.name} = {{")
    L.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    L.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    L.append(f"    .line_height = {ascent + descent},")
    L.append(f"    .base_line = {descent},")
    L.append("    .subpx = LV_FONT_SUBPX_NONE,")
    L.append("    .underline_position = 0,")
    L.append("    .underline_thickness = 0,")
    L.append("    .dsc = &font_dsc")
    L.append("};")
    with open(a.out, "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"{a.out}: {len(chars)} glyphs, {len(bitmap)} bitmap bytes, line_height {ascent + descent}")


if __name__ == "__main__":
    main()
